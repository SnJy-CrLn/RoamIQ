import os
import datetime


def save_document(response_text: str):
    """Export travel plan to a Markdown file."""

    # Get project root directory
    root_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

    # Create documents directory
    directory = os.path.join(root_dir, "documents")
    os.makedirs(directory, exist_ok=True)

    # Create Markdown content with metadata
    markdown_content = f"""# 🌍 RoamIQ - AI Travel Plan

**Generated:** {datetime.datetime.now().strftime('%Y-%m-%d at %H:%M')}

**Created by:** RoamIQ Travel Agent

---

{response_text}

---

*This travel plan was generated by AI.
Please verify all information, especially prices,
operating hours, and travel details.*
"""

    try:
        # Generate timestamp-based filename
        timestamp = datetime.datetime.now().strftime("%Y-%m-%d_%H-%M-%S")

        filename = f"AI_Travel_Plan_{timestamp}.md"
        file_path = os.path.join(directory, filename)

        # Write Markdown file
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(markdown_content)

        print(f"Markdown file saved: {file_path}")

        return file_path

    except Exception as e:
        print(f"Error saving markdown file: {e}")
        return None
