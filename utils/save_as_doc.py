
import os
import tempfile
import datetime


def save_document(response_text: str):
    """Generate a temporary Markdown travel document."""

    try:
        # Create a temporary directory
        temp_dir = tempfile.gettempdir()

        # Generate timestamp-based filename
        timestamp = datetime.datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
        filename = f"RoamIQ_Travel_Plan_{timestamp}.md"

        file_path = os.path.join(temp_dir, filename)

        # Create Markdown content
        markdown_content = f"""# 🌍 RoamIQ - AI Travel Plan

**Generated:** {datetime.datetime.now().strftime('%Y-%m-%d at %H:%M')}

**Created by:** RoamIQ Travel Agent

---

{response_text}

---

*This travel plan was generated by AI.
Please verify important travel details before your journey.*
"""

        # Write Markdown file
        with open(file_path, "w", encoding="utf-8") as file:
            file.write(markdown_content)

        return file_path

    except Exception as e:
        print(f"Error saving Markdown document: {e}")
        return None
