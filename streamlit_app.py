
import streamlit as st
from datetime import datetime
import requests

BASE_URL = "http://localhost:8000"

st.set_page_config(
    page_title="RoamIQ",
    page_icon="🌍",
    layout="centered",
    initial_sidebar_state="expanded"
)

st.title("🌍 RoamIQ")

st.header(
    "Hi! Greetings from my side. "
    "I'll help you plan your upcoming trip seamlessly. "
    "Let me know where you wanna go..."
)

# Initialize chat history
if "messages" not in st.session_state:
    st.session_state.messages = []

# Display previous conversations
for message in st.session_state.messages:

    with st.chat_message(message["role"]):
        st.markdown(message["content"])

# User input
user_input = st.chat_input("Plan a trip to Goa for 5 days...")

if user_input:

    # Display user message
    st.session_state.messages.append({
        "role": "user",
        "content": user_input
    })

    with st.chat_message("user"):
        st.markdown(user_input)

    # Call FastAPI backend
    with st.chat_message("assistant"):

        with st.spinner("RoamIQ is planning your trip..."):

            try:
                payload = {"query": user_input}

                response = requests.post(
                    f"{BASE_URL}/query",
                    json=payload,
                    timeout=180
                )

                response.raise_for_status()

                answer = response.json().get(
                    "answer",
                    "No answer returned."
                )

                markdown_content = f"""
                            ### ✈️ Your Travel Plan
                            
                            **Generated at:** {datetime.now().strftime('%Y-%m-%d %H:%M')}
                            
                            **Created by:** RoamIQ's Travel Agent
                            
                            ---
                            
                            {answer}
                            
                            ---
                            
                            *This plan was generated by AI. Please verify
                            prices, locations and other travel details before proceeding.*
                            
                            Have an excellent trip! 🌍
                """

                st.markdown(markdown_content)

                st.session_state.messages.append({
                    "role": "assistant",
                    "content": markdown_content
                })

            except requests.exceptions.RequestException as e:
                st.error(f"Could not connect to RoamIQ API: {e}")

            except Exception as e:
                st.error(f"Something went wrong: {e}")
