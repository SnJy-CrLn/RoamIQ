import streamlit as st
from datetime import datetime
import requests
import sys

BASE_URL = "https://localhost:8000"

st.set_page_config(
    page_title= "RoamIQ",
    page_icon="🌍",
    layout="centered",
    initial_sidebar_state="expanded"
)
st.title("RoamIQ")
#initialise chat history
if "messages" not in st.session_state:
    st.session_state.messages = []
st.header("Hi! Greetings from my side. I'll help you plan your upcoming trip seamlessly. Let me know where you wanna go ...")

with st.form(key="query_form", clear_on_submit=True):
    user_input = st.text_input("user Input", placeholder="Plan a trip to Goa for 5 days...")
    submit_button = st.form_submit_button("send")

if submit_button and user_input.strip():
    try:
        with st.spinner("Thinking..."):
            payload = {"question": user_input}
            response = requests.post(f"{BASE_URL}/query", json=payload)
        if response.status_code == 200:
            answer = response.json().get("answer", "No answer returned.")
            markdown_content = f"""
              TRAVEL PLAN

              Generated at: {datetime.now().strftime('%Y-%m-%d at %H:%M')} 
              Created by: RoamIQ's travel agent

              ---

              {answer}

              ---

              This plan was generated by an AI. So before proceeding verify the details like prices, locations once.
              Have an excellent trip !!!  
            """
            st.markdown(markdown_content)
        else:
            st.error('Bot failed to respond. ' + response.text)
    except Exception as e:
        raise f"The response failed due to {e}"